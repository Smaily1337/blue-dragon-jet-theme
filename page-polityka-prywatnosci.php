    <h2>Na czym polega zbieranie informacji o plikach cookies?</h2>
    <p>Nasz Serwis korzysta z plików cookies. Tzw. „ciasteczka" to dane informatyczne, a w szczególności pliki tekstowe, które przechowywane są w urządzeniach końcowych użytkowników. Przeznaczone są one do korzystania ze stron internetowych. Pliki te, co do zasady, zawierają nazwę strony internetowej, z której pochodzą, czas przechowywania ich na urządzeniu oraz swój niepowtarzalny numer. Podmiotem, który zamieszcza na urządzeniu końcowym Użytkownika Serwisu pliki cookies oraz uzyskuje do nich dostęp jest Operator Serwisu.</p>
    <p>W ramach Serwisu stosowane są dwa rodzaje plików cookies:<br>
    – „sesyjne" (session cookies) – pozostają na urządzeniu użytkownika, aż do czasu wylogowania, opuszczenia strony internetowej lub wyłączenia oprogramowania (przeglądarki internetowej).<br>
    – „stałe" (persistent cookies) – pozostają na urządzeniu użytkownika przez czas określony w parametrach plików cookies lub do czasu ich usunięcia przez użytkownika.</p>
